"""
Dynamic Prompt Engine for Mission-Critical Multi-Agent Orchestration.
Compiles base agent prompts with current state, user feedback overrides,
and context windows into hallucination-free dynamic task prompts.
"""

import os
from typing import Dict, Any, Optional
from orchestration.state.state_manager import StateManager


class DynamicPromptEngine:
    """Compiles battle-tested dynamic prompts for agents based on state and feedback."""

    def __init__(self, agents_dir: str = "orchestration/agents",
                 state_manager: Optional[StateManager] = None) -> None:
        """Initializes prompt engine with path to agents system prompt directory."""
        self.agents_dir = os.path.abspath(agents_dir)
        self.state_manager = state_manager or StateManager()

    def get_agent_seed_prompt(self, agent_filename: str) -> str:
        """Reads the static seed prompt for a given agent file."""
        file_path = os.path.join(self.agents_dir, agent_filename)
        if not os.path.exists(file_path):
            raise FileNotFoundError(f"Agent prompt file not found: {file_path}")
        with open(file_path, "r", encoding="utf-8") as f:
            return f.read()

    def compile_dynamic_prompt(
        self,
        agent_role: str,
        agent_filename: str,
        current_prd: Optional[str] = None,
        task_specific_instruction: Optional[str] = None
    ) -> str:
        """
        Synthesizes base agent prompt, state parameters, feedback history,
        preceding outputs, and zero-hallucination rules into an executable runtime prompt.
        """
        base_prompt = self.get_agent_seed_prompt(agent_filename)
        state = self.state_manager.get_state()

        # Collect relevant user feedback for this agent or general instructions
        user_feedback = state.get("user_feedback_history", [])
        agent_feedback = [
            f["feedback_text"] for f in user_feedback
            if f.get("target_agent") in [agent_role, "ALL", "Chief Manager & Orchestrator"]
        ]

        # Preceding outputs summary
        agent_outputs = state.get("agent_outputs", {})
        context_outputs_summary = []
        for role, output_data in agent_outputs.items():
            if role != agent_role:
                summary_snippet = output_data.get("raw_output", "")[:1000]
                context_outputs_summary.append(f"--- Output from [{role}] ---\n{summary_snippet}\n")

        # Assemble Dynamic Sections
        dynamic_context_header = f"""
================================================================================
DYNAMIC EXECUTION CONTEXT (AUTOGENERATED BY CHIEF ORCHESTRATOR)
Current Phase: {state.get('current_phase', 'UNKNOWN')}
Micro-Step Index: {state.get('current_micro_step', 0)}
Target Agent: {agent_role}
System Integrity Status: {state.get('system_health', {}).get('status', 'HEALTHY')}
================================================================================
"""

        prd_section = ""
        if current_prd:
            prd_section = f"\n### ACTIVE PRODUCT REQUIREMENT DOCUMENT (PRD)\n{current_prd}\n"

        feedback_section = ""
        if agent_feedback:
            feedback_section = "\n### REAL-TIME USER FEEDBACK OVERRIDES (MANDATORY COMPLIANCE)\n"
            for idx, fb in enumerate(agent_feedback, 1):
                feedback_section += f"{idx}. {fb}\n"

        task_section = ""
        if task_specific_instruction:
            task_section = f"\n### IMMEDIATE MICRO-PHASE TASK INSTRUCTION\n{task_specific_instruction}\n"

        preceding_context_section = ""
        if context_outputs_summary:
            preceding_context_section = "\n### PREVIOUS AGENT OUTPUT CONTEXT\n" + "\n".join(context_outputs_summary)

        hallucination_guardrail = """
================================================================================
CRITICAL MISSION-CRITICAL & ZERO-HALLUCINATION DIRECTIVE:
1. Grounding Rule: You MUST rely exclusively on explicit formulas, schemas, datasheets, or PRD specs.
2. Negative Constraint: Do NOT create imaginary packages, non-standard APIs, synthetic register offsets, or speculative functions.
3. Verification Checklist: You must append a 'Self-Audit & Grounding Verification' section to your output detailing line-by-line justification.
4. Aerospace Standards: Code must be modular, fully typed, PEP-8 / CMSIS compliant, and free of race conditions or memory leaks.
================================================================================
"""

        compiled_prompt = (
            f"{base_prompt}\n\n"
            f"{dynamic_context_header}\n"
            f"{prd_section}"
            f"{task_section}"
            f"{feedback_section}"
            f"{preceding_context_section}\n"
            f"{hallucination_guardrail}"
        )

        # Store in state manager for auditability
        self.state_manager.store_dynamic_prompt(agent_role, compiled_prompt)
        return compiled_prompt


if __name__ == "__main__":
    dpe = DynamicPromptEngine()
    print("Dynamic Prompt Engine initialized successfully.")
